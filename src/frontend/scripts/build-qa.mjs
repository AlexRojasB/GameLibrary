import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const frontend = fileURLToPath(new URL('../', import.meta.url));

function httpsOrigin(value, name) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${name} must be an absolute HTTPS origin.`);
  }
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash
      || url.pathname !== '/' || url.hostname === 'localhost' || !url.hostname.includes('.')) {
    throw new Error(`${name} must be an HTTPS origin without credentials, path, query or fragment.`);
  }
  return url.origin;
}

export function qaEnvironment(env) {
  const apiBaseUrl = httpsOrigin(env.QA_API_BASE_URL, 'QA_API_BASE_URL');
  const supabaseUrl = httpsOrigin(env.QA_SUPABASE_URL, 'QA_SUPABASE_URL');
  if (!/^https:\/\/[a-z0-9]{20}\.supabase\.co$/.test(supabaseUrl)
      || supabaseUrl === 'https://iramzxpjbnldhebykzhx.supabase.co') {
    throw new Error('QA_SUPABASE_URL must select a separate hosted QA project, not the existing development project.');
  }
  const supabaseKey = env.QA_SUPABASE_PUBLISHABLE_KEY;
  if (typeof supabaseKey !== 'string' || !/^sb_publishable_[A-Za-z0-9_-]+$/.test(supabaseKey)) {
    throw new Error('QA_SUPABASE_PUBLISHABLE_KEY must be a public publishable key, never a server secret or JWT.');
  }
  // Explicit allowlist: never serialize process.env or any server-side configuration.
  return { apiBaseUrl, supabaseUrl, supabaseKey, e2e: { enabled: false } };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const environment = qaEnvironment(process.env);
    writeFileSync(new URL('../src/environments/environment.qa.generated.ts', import.meta.url),
      `// Generated by scripts/build-qa.mjs; public values only.\nexport const environment = ${JSON.stringify(environment, null, 2)};\n`);
    const result = spawnSync(process.execPath,
      ['node_modules/@angular/cli/bin/ng.js', 'build', '--configuration', 'production,qa'],
      { cwd: frontend, stdio: 'inherit' });
    if (result.error) throw new Error('Unable to start the Angular build.');
    process.exitCode = result.status ?? 1;
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
